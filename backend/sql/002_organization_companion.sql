BEGIN;

CREATE TABLE organizations (
    organization_id VARCHAR(36) PRIMARY KEY,
    organization_name VARCHAR(150) NOT NULL,
    organization_type VARCHAR(50) NOT NULL
        CHECK (organization_type IN ('bank', 'hospital', 'ngo', 'rto', 'others')),
    email VARCHAR(255) NOT NULL,
    address TEXT NOT NULL,
    approval_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    approval_remarks TEXT,
    logo_url TEXT,
    document_type TEXT NOT NULL,
    document_url TEXT NOT NULL,
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX organizations_email_lower_key ON organizations (lower(email));

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL REFERENCES organizations(organization_id),
    name VARCHAR(120) NOT NULL,
    description TEXT,
    price_inr NUMERIC(10,2) NOT NULL CHECK (price_inr >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE companions (
    companion_id VARCHAR(36) PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL REFERENCES organizations(organization_id),
    name VARCHAR(100) NOT NULL,
    dob DATE,
    gender VARCHAR(20),
    email VARCHAR(255) NOT NULL,
    mobile VARCHAR(15) NOT NULL,
    address TEXT,
    identity_proof_url TEXT,
    photo_url TEXT,
    speciality VARCHAR(100),
    experience_years NUMERIC(4,1) CHECK (experience_years >= 0),
    languages_known TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    availability_status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'unavailable', 'busy')),
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX companions_email_lower_key ON companions (lower(email));

CREATE TABLE companion_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    companion_id VARCHAR(36) NOT NULL REFERENCES companions(companion_id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    UNIQUE (companion_id, service_id)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    companion_id VARCHAR(36) REFERENCES companions(companion_id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    organization_id VARCHAR(36) NOT NULL REFERENCES organizations(organization_id),
    rejection_reason TEXT,
    assigned_at TIMESTAMPTZ,
    service_notes TEXT,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    scheduled_at TIMESTAMPTZ NOT NULL,
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    pickup_address TEXT,
    duration INTEGER NOT NULL CHECK (duration > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'rejected', 'assigned',
                         'on_the_way', 'arrived', 'in_progress', 'completed', 'cancelled')),
    start_code_hash VARCHAR(255),
    end_code_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    price_inr NUMERIC(10,2) NOT NULL CHECK (price_inr >= 0),
    cancelled_at TIMESTAMPTZ,
    cancelled_by VARCHAR(20) CHECK (cancelled_by IN ('customer', 'organization')),
    cancellation_reason TEXT,
    rejected_at TIMESTAMPTZ
);

COMMIT;