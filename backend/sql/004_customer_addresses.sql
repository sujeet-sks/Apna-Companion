BEGIN;

CREATE TABLE customer_addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    label VARCHAR(20) NOT NULL CHECK (label IN ('HOME', 'WORK', 'OTHER')),
    house_no VARCHAR(50) NOT NULL,
    building_street VARCHAR(150) NOT NULL,
    area_locality VARCHAR(150),
    landmark VARCHAR(150),
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    pincode CHAR(6) NOT NULL CHECK (pincode ~ '^[0-9]{6}$'),
    country VARCHAR(50) NOT NULL DEFAULT 'India',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    latitude NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX customer_addresses_customer_id_idx
    ON customer_addresses (customer_id);

CREATE UNIQUE INDEX customer_addresses_one_active_default_idx
    ON customer_addresses (customer_id)
    WHERE is_default AND is_active;

COMMIT;