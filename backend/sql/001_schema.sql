BEGIN;

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address TEXT NOT NULL,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'suspended'))
);

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name VARCHAR(120) NOT NULL,
    price_inr NUMERIC(10,2) NOT NULL CHECK (price_inr >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE verification_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('customer', 'companion', 'organization', 'admin')),
    identifier VARCHAR(254) NOT NULL,
    purpose VARCHAR(20) NOT NULL
        CHECK (purpose IN ('register', 'password_reset')),
    code_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('customer', 'companion', 'organization', 'admin')),
    name VARCHAR(100) NOT NULL,
    login_identifier VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255),
    organization_id BIGINT REFERENCES organizations(id),
    status VARCHAR(12) NOT NULL DEFAULT 'active'
        CHECK (status IN ('invited', 'active', 'disabled')),
    UNIQUE (role, login_identifier)
);

CREATE TABLE login_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    companion_id BIGINT REFERENCES users(id),
    scheduled_at TIMESTAMPTZ NOT NULL,
    pickup_address TEXT NOT NULL,
    pickup_latitude NUMERIC(9,6),
    pickup_longitude NUMERIC(9,6),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'assigned', 'accepted',
            'in_progress', 'completed', 'cancelled'
        )),
    quoted_amount_inr NUMERIC(10,2) NOT NULL
        CHECK (quoted_amount_inr >= 0),
    start_code_hash VARCHAR(255),
    end_code_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payments (
    booking_id BIGINT PRIMARY KEY REFERENCES bookings(id),
    status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'failed')),
    gateway_order_id VARCHAR(120) UNIQUE,
    gateway_payment_id VARCHAR(120) UNIQUE
);

CREATE TABLE ratings (
    booking_id BIGINT PRIMARY KEY REFERENCES bookings(id),
    score SMALLINT NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment TEXT
);

INSERT INTO categories (name)
VALUES ('Banking'), ('Hospital'), ('RTO'), ('Domestic');

COMMIT;